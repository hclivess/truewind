// docs/VALIDATION.md: every quantity the test suite checks, with its expected value or range, tolerance, source, the
// test that checks it and its current result. Collected from
//   - the registers the validation tests write as they run (test/lib/validation.mjs: test/out/validation/*.json:
//     micro-waves, micro-rope, passages), each check with its own measured value and result;
//   - the sea trials' report (test/out/seatrial.json, else seatrial-quick.json), aggregated per metric over the
//     classes and conditions (the ranges and sources in test/seatrial/refs.mjs);
//   - the catalogue of the older tests' checks (docs/validation-catalog.json: quantity, expected, tolerance, source,
//     line, read off each test's code and comments), with each test file's result from its last run
//     (test/out/validation/_runs.json: --run runs them).
//
//   node tools/validation-doc.mjs              rebuild the document from what is on disk
//   node tools/validation-doc.mjs --run        run every test/*.mjs first (JOBS=n in parallel, TIMEOUT_MIN per test,
//                                              default 30; SKIP=seatrial,passages: the long ones are skipped by default,
//                                              run them on their own), then rebuild
//   ONLY=rope,tide node tools/validation-doc.mjs --run   just those
import { readFileSync, writeFileSync, existsSync, readdirSync, mkdirSync } from 'node:fs';
import { spawn } from 'node:child_process';
import { cpus } from 'node:os';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const OUTV = `${ROOT}test/out/validation/`;
mkdirSync(OUTV, { recursive: true });
const E = process.env;
const runsFile = `${OUTV}_runs.json`;
const runs = existsSync(runsFile) ? JSON.parse(readFileSync(runsFile, 'utf8')) : {};

if (process.argv.includes('--run')) {
  const skip = new Set((E.SKIP ?? 'seatrial,passages,realraces,bench,bench-fleet').split(',').filter(Boolean));
  const only = E.ONLY ? new Set(E.ONLY.split(',')) : null;
  const files = readdirSync(`${ROOT}test`).filter((f) => f.endsWith('.mjs')).map((f) => f.slice(0, -4)).filter((f) => (only ? only.has(f) : !skip.has(f)));
  const n = +(E.JOBS || Math.max(2, cpus().length - 2)), lim = +(E.TIMEOUT_MIN || 30) * 60e3;
  let next = 0;
  const one = (f) => new Promise((res) => {
    const t0 = Date.now(); let out = '';
    const p = spawn(process.execPath, [`test/${f}.mjs`], { cwd: ROOT, stdio: ['ignore', 'pipe', 'pipe'] });
    p.stdout.on('data', (d) => { out += d; }); p.stderr.on('data', (d) => { out += d; });
    const timer = setTimeout(() => { p.kill(); out += '\nTIMEOUT'; }, lim);
    p.on('close', (code) => {
      clearTimeout(timer);
      const fails = out.split('\n').filter((l) => /\bFAIL\b|FAILED|Error|TIMEOUT/.test(l)).slice(0, 12).map((l) => l.trim().slice(0, 220));
      runs[f + '.mjs'] = { code, status: /TIMEOUT/.test(out) ? 'timeout' : code === 0 ? 'pass' : 'fail', secs: (Date.now() - t0) / 1000, when: new Date().toISOString(), fails };
      console.log(`${runs[f + '.mjs'].status.padEnd(7)} ${f} (${runs[f + '.mjs'].secs.toFixed(0)} s)${fails.length ? ': ' + fails[0] : ''}`);
      writeFileSync(runsFile, JSON.stringify(runs, null, 1));
      res();
    });
  });
  await Promise.all(Array.from({ length: n }, async () => { while (next < files.length) await one(files[next++]); }));
}

// ------------------------------------------------------------------ collect
const esc = (s) => String(s ?? '').replace(/\|/g, '/').replace(/\n/g, ' ');
const RES = { pass: 'pass', warn: 'WARN', fail: 'FAIL', info: 'info', timeout: 'TIMEOUT' };
const md = ['# Validation', '',
  'Every quantity the tests check: what is expected, within what tolerance, on whose authority, which test checks it, and what it gives now.',
  `Generated by \`node tools/validation-doc.mjs\` (\`--run\` reruns the tests first) on ${new Date().toISOString().slice(0, 16)}Z. The results are those of the last runs on disk; the sea trials and the passages are long and run on their own (\`node test/seatrial.mjs\`, \`node test/passages.mjs\`, or their \`QUICK=1\`).`, '',
  'Sections: 1. micro (waves, ropes) · 2. sea trials · 3. passages · 3b. real races · 4. the other tests (catalogue of their checks).', ''];
const regs = existsSync(OUTV) ? readdirSync(OUTV).filter((f) => f.endsWith('.json') && !f.startsWith('_')).map((f) => JSON.parse(readFileSync(OUTV + f, 'utf8'))) : [];
const regTable = (R) => {
  md.push(`### ${R.test} (${R.rows.filter((r) => r.status === 'pass').length} pass, ${R.rows.filter((r) => r.status === 'warn').length} warn, ${R.rows.filter((r) => r.status === 'fail').length} fail; run ${R.generated.slice(0, 16)}Z)`, '',
    '| Quantity | Expected | Tolerance | Source | Measured | Result |', '|---|---|---|---|---|---|');
  for (const r of R.rows) md.push(`| ${esc((r.section ? r.section + ': ' : '') + r.quantity)} | ${esc(r.expected)} | ${esc(r.tol)} | ${esc(r.source)} | ${esc(r.measured)} | ${RES[r.status] || r.status} |`);
  md.push('');
};
md.push('## 1. Micro: waves and ropes', '');
for (const R of regs.filter((r) => /micro/.test(r.test))) regTable(R);
if (!regs.some((r) => /micro/.test(r.test))) md.push('(not run yet: `node test/micro-waves.mjs`, `node test/micro-rope.mjs`)', '');

// ------------------------------------------------------------------ sea trials, aggregated per metric
md.push('## 2. Sea trials (test/seatrial.mjs)', '');
const stFile = [`${ROOT}test/out/seatrial.json`, `${ROOT}test/out/seatrial-quick.json`].find(existsSync);
if (stFile) {
  const S = JSON.parse(readFileSync(stFile, 'utf8'));
  // the quantity, the expected range and the source for each check key (test/seatrial/refs.mjs, judge.mjs)
  const DEF = [
    [/^upwindSpeed$|^beatAfter|^leaveSpeed$|^beamSpeed$|^broadSpeed$/, 'boat speed against the class\'s baked polar at the wind and angle sailed', 'flat & steady: +-12% (warn 20%); gusts or sea: 0.70-1.12 of it (warn 0.55-1.25)', 'the class polar (data/sails); Gerritsma & Keuning / Larsson & Eliasson (added resistance)'],
    [/^known/, 'speed against published data (beat VMG, 90 deg reach; the J Class upwind boat-speed band)', '+-15% (warn 25%)', 'ORC certificates (TP52 Caballo Loco, J/24 GER 907, J/122 J-Curve, Folkboat NED 866, J/70); Yachting World (J Class)'],
    [/^heel:/, 'heel held by a depowering crew', '5 s mean not above targetHeel + 10 deg for more than 5 s (warn: +5 for 10 s)', 'the class targetHeel; the task'],
    [/^courseRms$/, 'heading rms on a beam reach', 'flat: 3 deg (gusts 3.9); sea: 3 + 3 Hs deg; warn 1.7x', 'the task (+-2-3 deg); test/seakeeping.mjs after Gerritsma, Keuning & Versluis 1993; Marchaj 1986'],
    [/^zigzag$/, 'limit-cycle zig-zag of the heading on a reach', 'no autocorrelation peak > 0.4 at 1.5-30 s with amplitude > 1.5 deg', 'est.'],
    [/^fixedHelm$/, 'directional stability: heading drift with the helm fixed on a reach', '< 15 deg in 10 s and < 60 deg in 30 s (warn < 30 in 10 s)', 'Larsson & Eliasson (balance); Marchaj, Seaworthiness ch. 7'],
    [/^weatherHelm$/, 'steady weather helm upwind', '1.5-6 deg (warn -1-9)', 'Larsson & Eliasson; test/helm.mjs (2-4 deg design aim)'],
    [/^tack[12]$/, 'tack: turn time and speed loss; no stall in irons', 'turn 2-15 s (< 6 m), 3-18 s (< 15 m), 6-35 s; loss < 50% (light boats 60%), warn 70%', 'Masuyama, Fukasawa & Sasagawa, CSYS 1995 (order); est.'],
    [/^gybe$/, 'gybe completed', '< 15 s (< 30 s from 15 m)', 'est.'],
    [/^roll$|^pitch$/, 'roll and pitch rms on a beam reach', 'sea: roll 6.5, pitch 3.5 deg x sqrt(Hs/0.8) (x1.25 under 8 m); flat: roll < 2 deg', 'test/seakeeping.mjs section 4'],
    [/^rigSF$/, 'rig safety factor: strength / peak load of the worst part', '>= 2 (warn 1.5)', 'Nordic Boat Standard; Skene; test/damage.mjs'],
    [/^sailSF$/, 'sail cloth safety factor', '>= 2 (warn 1.5)', 'js/damage.js cloth strengths'],
    [/^dismast$|^boom$|^sailTear$/, 'no dismasting, broken boom or torn sail in seamanlike sailing', 'none to 32 kn', 'the task'],
    [/^capsize$/, 'no capsize (keelboats); dinghies and cats only from 18-25 kn', 'none', 'the task'],
    [/^spike:/, 'load spikes on the steady legs: a load against its own 1 s mean', '< 3x (fail > 6x)', 'est.'],
    [/^chatter:/, 'sheet-load chatter: local extrema per second', '< 8/s (fail > 25/s)', 'est.'],
    [/^heaveTo$/, 'heaving to: she slows and lies quietly', 'under half her speed and under 2.5 kn', 'seamanship (est.)'],
    [/^nan$|^run$/, 'no NaN, no crash', 'none', ''],
    [/^unplanned$/, 'no tack or gybe unbidden (broach, round-up, crash gybe)', 'none', 'seamanship'],
    [/^maxHeel$|^aground$/, 'no knockdown past target + 35 deg; never aground', '', 'est.'],
  ];
  const agg = {};
  for (const r of S.results) for (const c of r.checks) {
    if (c.s === 'info') continue;
    const d = DEF.find(([re]) => re.test(c.k)); if (!d) continue;
    const a = agg[d[1]] || (agg[d[1]] = { d, pass: 0, warn: 0, fail: 0, worst: [] });
    a[c.s]++;
    if (c.s === 'fail' && a.worst.length < 3) a.worst.push(`${r.cls} ${r.cond} ${r.mode}: ${c.v}`);
  }
  md.push(`From ${stFile.split('/').pop()} (${S.results.length} trials, ${S.generated.slice(0, 16)}Z; the per-class tables are in test/out/${stFile.split('/').pop().replace('.json', '.md')}).`, '',
    '| Quantity | Expected | Source | Trials pass / warn / fail | Worst failures | Result |', '|---|---|---|---|---|---|');
  for (const a of Object.values(agg)) md.push(`| ${esc(a.d[1])} | ${esc(a.d[2])} | ${esc(a.d[3])} | ${a.pass} / ${a.warn} / ${a.fail} | ${esc(a.worst.join('; '))} | ${a.fail ? 'FAIL' : a.warn ? 'WARN' : 'pass'} |`);
  md.push('');
} else md.push('(not run yet: `QUICK=1 node test/seatrial.mjs`)', '');

// ------------------------------------------------------------------ passages
md.push('## 3. Passages (test/passages.mjs)', '');
const pr = regs.filter((r) => /^passages/.test(r.test));
for (const R of pr) regTable(R);
if (!pr.length) md.push('(not run yet: `QUICK=1 node test/passages.mjs`)', '');

// ------------------------------------------------------------------ real races
md.push('## 3b. Real races (test/realraces.mjs)', '', 'Cowes Week 2026 races sailed on their real courses in the measured wind and the real tide, against the real fleets\' elapsed times (test/realdata/, built by tools/fetch-realraces.mjs).', '');
const rr = regs.filter((r) => /^realraces/.test(r.test));
for (const R of rr) regTable(R);
if (!rr.length) md.push('(not run yet: `QUICK=1 node test/realraces.mjs`)', '');

// ------------------------------------------------------------------ the catalogue of the other tests
md.push('## 4. The other tests', '', 'The checks of every other test, read off its code and comments (docs/validation-catalog.json; regenerate it when a test changes). Result: the test file\'s last run (a file fails as a whole; its failing lines are quoted). *unchecked*: printed for comparison, not asserted.', '');
const cat = JSON.parse(readFileSync(`${ROOT}docs/validation-catalog.json`, 'utf8'));
const byTest = {};
for (const e of cat) (byTest[e.test] ||= []).push(e);
for (const t of Object.keys(byTest).sort()) {
  const R = runs[t];
  md.push(`### ${t} — ${R ? `${RES[R.status] || R.status} (${R.when.slice(0, 16)}Z, ${R.secs.toFixed(0)} s)` : 'not run'}`, '');
  if (R && R.fails && R.fails.length) md.push('Failing lines: ' + R.fails.map((l) => '`' + esc(l).replace(/`/g, "'") + '`').join(' · '), '');
  md.push('| Quantity | Expected | Tolerance | Source | Line | Result |', '|---|---|---|---|---|---|');
  for (const e of byTest[t]) md.push(`| ${esc((e.section ? e.section + ': ' : '') + e.quantity)} | ${esc(e.expected)} | ${esc(e.tol)} | ${esc(e.source)} | ${e.line ?? ''} | ${e.checked === false ? 'unchecked' : R ? RES[R.status] || R.status : '-'} |`);
  md.push('');
}
// tests on disk with no catalogue entry and no register (added since the catalogue was made)
const known = new Set([...Object.keys(byTest), ...regs.map((r) => r.test), 'seatrial.mjs', 'passages.mjs', 'realraces.mjs']);
const missing = readdirSync(`${ROOT}test`).filter((f) => f.endsWith('.mjs') && !known.has(f));
if (missing.length) {
  md.push('### Not catalogued yet', '', 'These tests are newer than docs/validation-catalog.json: their checks are not listed above (add entries to the catalogue, or have them register their checks through test/lib/validation.mjs).', '', '| Test | Last run |', '|---|---|');
  for (const f of missing) { const R = runs[f]; md.push(`| ${f} | ${R ? `${RES[R.status] || R.status} (${R.when.slice(0, 16)}Z)` : 'not run'} |`); }
  md.push('');
}
writeFileSync(`${ROOT}docs/VALIDATION.md`, md.join('\n') + '\n');
console.log(`docs/VALIDATION.md: ${regs.reduce((s, r) => s + r.rows.length, 0)} registered checks, ${cat.length} catalogued, ${Object.keys(runs).length} test runs`);
